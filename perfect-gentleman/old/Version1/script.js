    /* ── Active language ─────────────────────────────────────── */
    let currentLang = (typeof SITE_CONFIG !== 'undefined')
      ? SITE_CONFIG.defaultLanguage
      : 'en';

    function t(key) { return translations[currentLang][key] || key; }

    function setLang(lang) {
      currentLang = lang;
      document.documentElement.lang = lang;

      // Update all data-i18n elements
      document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key] !== undefined) el.textContent = translations[lang][key];
      });

      // Update lang buttons (desktop + mobile)
      ['btn-en','btn-no','m-btn-en','m-btn-no'].forEach(id => {
        const el = document.getElementById(id);
        if (el) el.classList.toggle('active', id.includes(lang === 'en' ? 'en' : 'no'));
      });

      renderHoursTable();
    }

    /* ── Hours table ─────────────────────────────────────────── */
    function renderHoursTable() {
      const today = new Date().getDay(); // 0=Sun
      const jsToOurs = [6,0,1,2,3,4,5]; // map JS day to our array index
      const todayIdx = jsToOurs[today];

      const tbody = document.getElementById('hours-table');
      tbody.innerHTML = HOURS.map((h, i) => {
        const dayName = currentLang === 'no' ? h.no : h.en;
        const timeStr = h.open ? `${h.open} – ${h.close}` : t('hours.closed');
        const isToday = i === todayIdx;
        const isClosed = !h.open;
        return `<tr class="${isToday ? 'today' : ''} ${isClosed ? 'closed' : ''}">
          <td>${dayName}</td>
          <td>${timeStr}</td>
        </tr>`;
      }).join('');
    }

    /* ── Google stars ─────────────────────────────────────────── */
    function renderStars(score) {
      const starsEl = document.getElementById('g-stars');
      if (!starsEl) return;
      const full = Math.floor(score);
      const half = score - full >= 0.25 && score - full < 0.75;
      const empty = 5 - full - (half ? 1 : 0);
      starsEl.innerHTML =
        '★'.repeat(full).split('').map(() => `<span class="star-full">★</span>`).join('') +
        (half ? `<span class="star-half">½</span>` : '') +
        '★'.repeat(empty).split('').map(() => `<span class="star-empty">★</span>`).join('');
    }

    /* ── Navbar scroll ────────────────────────────────────────── */
    window.addEventListener('scroll', () => {
      document.getElementById('navbar').classList.toggle('scrolled', window.scrollY > 50);
    });

    /* ── Mobile menu ──────────────────────────────────────────── */
    function toggleMenu() {
      const menu = document.getElementById('mobile-menu');
      const ham  = document.getElementById('hamburger');
      menu.classList.toggle('open');
      ham.classList.toggle('open');
    }

    /* ── Scroll reveal ────────────────────────────────────────── */
    const observer = new IntersectionObserver(entries => {
      entries.forEach(e => { if (e.isIntersecting) e.target.classList.add('visible'); });
    }, { threshold: 0.1 });
    document.querySelectorAll('.reveal').forEach(el => observer.observe(el));

    /* ── Custom cursor ────────────────────────────────────────── */
    const cursorEnabled = (typeof SITE_CONFIG !== 'undefined')
